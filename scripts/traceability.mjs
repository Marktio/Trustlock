// Builds docs/TRACEABILITY.md: every requirement from the System Documentation, which automated tests prove it, and its status.
// Test titles carry requirement IDs in square brackets, e.g. it("pays once [FR-5.9, NFR-2.4]"), so the table cannot drift from the tests.
// Requirements with no test must be explained in docs/trace-notes.json. A Must with neither a test nor a note is reported as a gap.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const requirements = JSON.parse(readFileSync(path.join(root, "docs/requirements.json"), "utf8"));
const notes = JSON.parse(readFileSync(path.join(root, "docs/trace-notes.json"), "utf8"));

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = path.join(dir, name);
    if (name === "node_modules" || name === ".next") return [];
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const files = [...walk(path.join(root, "src")).filter((f) => f.endsWith(".test.ts")), ...walk(path.join(root, "e2e")).filter((f) => f.endsWith(".spec.ts"))];

/** "FR-6.1 to FR-6.7" means FR-6.1 through FR-6.7. */
function expand(list) {
  const ids = new Set();
  const parts = list.split(",").map((s) => s.trim());
  for (const part of parts) {
    const range = part.match(/^((?:N)?FR-\d+)\.(\d+) to ((?:N)?FR-\d+)\.(\d+)$/);
    if (range) for (let i = Number(range[2]); i <= Number(range[4]); i++) ids.add(`${range[1]}.${i}`);
    else if (/^(N?FR)-\d+\.\d+$/.test(part)) ids.add(part);
  }
  return ids;
}

const byReq = new Map();
let testCount = 0;
for (const file of files) {
  const rel = path.relative(root, file);
  const text = readFileSync(file, "utf8");
  for (const m of text.matchAll(/\b(?:it|test)\(\s*(["`])((?:\\.|(?!\1).)*)\1/g)) {
    const title = m[2];
    testCount += 1;
    const tag = title.match(/\[([^\]]*(?:FR|NFR)-[^\]]*)\]\s*$/);
    if (!tag) continue;
    for (const id of expand(tag[1])) {
      if (!byReq.has(id)) byReq.set(id, []);
      byReq.get(id).push({ file: rel, title: title.replace(/\s*\[[^\]]*\]\s*$/, "") });
    }
  }
}

const known = new Set(requirements.map((r) => r.id));
const unknown = [...byReq.keys()].filter((id) => !known.has(id));
if (unknown.length) console.warn("Tests mention unknown requirement IDs:", unknown.join(", "));

const rows = requirements.map((r) => {
  const tests = byReq.get(r.id) ?? [];
  const note = notes[r.id];
  const status = tests.length ? "Verified" : note?.status ?? (r.priority === "Must" ? "GAP" : "Not covered");
  return { ...r, tests, status, note: note?.note ?? "" };
});

const count = (f) => rows.filter(f).length;
const fr = (r) => r.id.startsWith("FR-");
const must = (r) => r.priority === "Must";
const summary = [
  ["Functional requirements (FR)", count(fr)],
  ["  Must", count((r) => fr(r) && must(r))],
  ["  Must with an automated test", count((r) => fr(r) && must(r) && r.status === "Verified")],
  ["  Must provided by Clerk (not built in this app)", count((r) => fr(r) && must(r) && r.status === "Provided by Clerk")],
  ["  Must planned, not built yet", count((r) => fr(r) && must(r) && r.status === "Planned")],
  ["  Must verified another way (manual or process)", count((r) => fr(r) && must(r) && r.status === "Manual")],
  ["  Must with no test and no explanation (gap)", count((r) => fr(r) && must(r) && r.status === "GAP")],
  ["Non-functional requirements (NFR)", count((r) => !fr(r))],
  ["  with an automated test", count((r) => !fr(r) && r.status === "Verified")],
];

const esc = (s) => s.replace(/\|/g, "\\|");
const cell = (r) =>
  r.tests.length
    ? r.tests.map((t) => `${esc(t.title)} (\`${t.file}\`)`).join("<br>")
    : r.note
      ? esc(r.note)
      : "";

let md = `# Requirement-to-test traceability

Generated by \`npm run trace\` from the test titles in \`src/**/*.test.ts\` and \`e2e/*.spec.ts\`. Do not edit by hand.
Requirement text and priorities come from the System Documentation (\`docs/requirements.json\`).
Requirements without a test are explained in \`docs/trace-notes.json\`.

**Automated tests found:** ${testCount} (${files.length} files)

## Summary

| Measure | Count |
|---|---|
${summary.map(([k, v]) => `| ${k} | ${v} |`).join("\n")}

Statuses: **Verified** = at least one automated test names this requirement. **Provided by Clerk** = the requirement is met by the authentication service, not by code in this repository. **Planned** = not built yet. **Manual** = checked by a person or by the pipeline, not by a unit test. **GAP** = a Must requirement with neither a test nor an explanation.

## Table

| ID | Priority | Requirement | Status | Tests or notes |
|---|---|---|---|---|
${rows.map((r) => `| ${r.id} | ${r.priority ?? "Must"} | ${esc(r.text.length > 140 ? r.text.slice(0, 137) + "…" : r.text)} | ${r.status} | ${cell(r)} |`).join("\n")}
`;

const gaps = rows.filter((r) => r.status === "GAP");
if (gaps.length) md += `\n## Gaps\n\n${gaps.map((r) => `- ${r.id}: ${r.text}`).join("\n")}\n`;

writeFileSync(path.join(root, "docs/TRACEABILITY.md"), md);
console.log(summary.map(([k, v]) => `${k}: ${v}`).join("\n"));
if (gaps.length) {
  console.error(`\n${gaps.length} Must requirement(s) have no test and no explanation: ${gaps.map((r) => r.id).join(", ")}`);
  process.exitCode = process.argv.includes("--strict") ? 1 : 0;
}
